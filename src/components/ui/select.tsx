function selectItemText(node: React.ReactNode): string {
  if (node === null || node === undefined || typeof node === "boolean") return "";
  if (typeof node === "string" || typeof node === "number") return String(node);
  if (Array.isArray(node)) return node.map(selectItemText).join(" ");
  if (React.isValidElement(node)) {
    return selectItemText((node.props as { children?: React.ReactNode }).children);
  }
  return "";
}

function countSelectItems(children: React.ReactNode): number {
  let count = 0;
  React.Children.forEach(children, (child) => {
    if (!React.isValidElement(child)) return;
    if (child.type === SelectItem) {
      count += 1;
    } else if (child.type === SelectGroup || child.type === React.Fragment) {
      count += countSelectItems((child.props as { children?: React.ReactNode }).children);
    }
  });
  return count;
}

function filterSelectChildren(children: React.ReactNode, query: string): React.ReactNode {
  const q = query.trim().toLowerCase();
  if (!q) return children;
  return React.Children.map(children, (child) => {
    if (!React.isValidElement(child)) return null;
    const element = child as React.ReactElement<{ children?: React.ReactNode }>;
    if (element.type === SelectItem) {
      return selectItemText(element.props.children).toLowerCase().includes(q) ? element : null;
    }
    if (element.type === SelectGroup || element.type === React.Fragment) {
      const filtered = filterSelectChildren(element.props.children, q);
      if (countSelectItems(filtered) === 0) return null;
      return React.cloneElement(element, {
        children: filtered,
      } as Partial<{ children?: React.ReactNode }>);
    }
    if (element.type === SelectSeparator) return null;
    return child;
  });
}

